"""Derives the initial commit's files from a project's Spec Kit stage
documents (constitution/specify/plan/tasks) at the `tech_review ->
repo_created` transition (see app/api/sync.py's `create_repository`).

Pure and I/O-free on purpose: no network, no LLM call, no widening of the
`stage` Literal (closed in schemas.py, api/stage_documents.py, the Postgres
CHECK in migrations/0019_stage_documents.sql, and the web STAGE_ORDER). The
seeded files here are just derived *views* over those four documents plus a
project's Policy Scope (app/models/schemas.py::PolicyScope), composed at
commit time — not a new document kind.

Derived views, one SeedFile per non-empty input:
  AGENTS.md                          constitution (or a stub)
  README.md                          specify (or a stub)
  docs/scope.md                      specify
  docs/architecture.md               plan
  docs/tasks.md                      tasks
  docs/conventions.md                the constitution's "Conventions" section (or a stub)
  .specify/memory/constitution.md    the constitution verbatim — this is what makes the
                                      engine's own `withConstitution()` (apps/engine/src/
                                      routes/projects.ts) inherit policy for desktop/engine
                                      users, since that's the exact path it reads
  docs/policy-scope.md               the project's policy scope, full template bodies +
                                      custom text — only when a scope was selected

Those are the paths for a repository the platform created. A repository the
user imported already has content, and the seed must never overwrite any of
it (plan 0027 M4): `fit_to_existing_repo` at the bottom of this module moves
the derived views under `docs/promptzone/` and drops whatever still collides.
"""

from __future__ import annotations

import posixpath
from dataclasses import dataclass
from datetime import datetime, timezone

from app.deployments.plan_profile import derive_stack_profile
from app.deployments.registry import get_template as get_deployment_template
from app.deployments.registry import (
    is_composed_scaffold,
    render_deployment_doc,
    template_files,
)
from app.models.schemas import Project
from app.policies.registry import render_policy_scope_doc

_PREAMBLE = (
    "<!-- Rules for AI coding agents here. Generated by PromptZone at repo "
    "creation; edit freely — never overwritten. -->\n\n"
)


@dataclass(frozen=True)
class SeedFile:
    path: str
    content: str
    # Git tree mode 100755 rather than 100644. Only deployment-template
    # scaffolds set this (a build script a workflow invokes); every derived
    # document below is a plain file.
    executable: bool = False


def _footer(project: Project) -> str:
    date = datetime.now(timezone.utc).date().isoformat()
    return f"\n\n<!-- Generated by PromptZone for project {project.id} on {date}. -->\n"


def _conventions_section(constitution: str | None) -> str | None:
    """Dumb heading scan: find a "Conventions" heading (any level) and return
    everything up to the next heading of the same or shallower level. No LLM
    call — a best-effort extraction, not a parse."""
    if not constitution:
        return None
    lines = constitution.splitlines()
    start = None
    start_level = 0
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.lower().lstrip("#").strip() == "conventions" and stripped.startswith("#"):
            start = i
            start_level = len(stripped) - len(stripped.lstrip("#"))
            break
    if start is None:
        return None
    end = len(lines)
    for j in range(start + 1, len(lines)):
        stripped = lines[j].strip()
        if stripped.startswith("#"):
            level = len(stripped) - len(stripped.lstrip("#"))
            if level <= start_level:
                end = j
                break
    section = "\n".join(lines[start:end]).strip()
    return section or None


def build_seed_files(project: Project, stage_docs: dict[str, str | None]) -> list[SeedFile]:
    """`stage_docs` maps stage name ("constitution"/"specify"/"plan"/"tasks")
    to its content, or is missing/None/empty for a stage never generated.
    Missing/empty stage doc -> that file is skipped, except AGENTS.md and
    README.md, which always get a stub — repo creation must never fail on a
    partially-planned project."""
    constitution = (stage_docs.get("constitution") or "").strip() or None
    specify = (stage_docs.get("specify") or "").strip() or None
    plan = (stage_docs.get("plan") or "").strip() or None
    tasks = (stage_docs.get("tasks") or "").strip() or None

    files: list[SeedFile] = []

    agents_body = constitution or (
        "No constitution has been generated for this project yet. "
        "Add project-specific rules for AI coding agents here."
    )
    files.append(SeedFile("AGENTS.md", _PREAMBLE + agents_body + _footer(project)))

    readme_lines = [f"# {project.name}", ""]
    readme_lines.append(
        f"Managed by PromptZone. See the project in the cloud workspace: "
        f"project id `{project.id}`."
    )
    readme_lines.append("")
    if specify:
        readme_lines.append("## Scope")
        readme_lines.append("")
        readme_lines.append(specify)
    else:
        readme_lines.append("## Scope")
        readme_lines.append("")
        readme_lines.append("No scope/spec has been generated for this project yet.")
    files.append(SeedFile("README.md", "\n".join(readme_lines) + _footer(project)))

    if specify:
        files.append(SeedFile("docs/scope.md", specify + _footer(project)))

    if plan:
        files.append(SeedFile("docs/architecture.md", plan + _footer(project)))

    if tasks:
        files.append(SeedFile("docs/tasks.md", tasks + _footer(project)))

    conventions = _conventions_section(constitution)
    if conventions:
        files.append(SeedFile("docs/conventions.md", conventions + _footer(project)))
    else:
        files.append(
            SeedFile(
                "docs/conventions.md",
                "Conventions are documented in `AGENTS.md` at the repo root."
                + _footer(project),
            )
        )

    if constitution:
        # This is what lets the engine's own `withConstitution()` inherit
        # policy for desktop/engine users (see module docstring) — it reads
        # exactly this path and, before this feature, the cloud never seeded
        # it at all.
        files.append(
            SeedFile(".specify/memory/constitution.md", constitution + _footer(project))
        )

    scope = project.policy_scope
    if scope is not None and (scope.selected or scope.custom_text.strip()):
        files.append(
            SeedFile("docs/policy-scope.md", render_policy_scope_doc(scope) + _footer(project))
        )

    return files


def build_deployment_files(
    project: Project,
    preview_url: str | None,
    plan_text: str | None = None,
    detected_runtime: str | None = None,
) -> list[SeedFile]:
    """The deployment template's scaffold, workflow and `docs/deployment.md`
    (ADR 0021), or an empty list when no template was selected.

    `plan_text` is the project's `plan` stage document, and it only matters to
    a template with a composed scaffold (ADR 0026): the runtime and the
    backing services are read off it by a keyword scan, which then *selects*
    among hand-written files. Nothing here generates a file, so this function
    stays as pure and as deterministic as it was — the same plan text seeds
    the same tree. `detected_runtime` is the imported repository's own
    manifests' answer to the same question (plan 0027); see
    `derive_stack_profile` for why it wins.

    Kept separate from `build_seed_files` rather than folded into it, for two
    reasons. These files are *verbatim scaffold* rather than derived views
    over stage documents, so the module docstring's contract above still
    holds exactly. And a project with no template must produce a byte-identical
    seed to the one it produced before this feature existed — which is much
    easier to keep true, and to test, when the two builders cannot interact.

    Pure and I/O-free in the same sense as its sibling: template files are
    read from this package's own directory, the way
    app/policies/registry.py::template_body already reads policy bodies. No
    network, no model call.
    """
    config = project.deployment_config
    if config is None:
        return []
    template = get_deployment_template(config.template_id)
    if template is None:
        # A selection that no longer resolves (a template withdrawn between
        # selection and repo creation) seeds nothing rather than failing the
        # transition: the repo and its AI context are still worth having.
        return []

    profile = derive_stack_profile(plan_text, detected_runtime)
    files = [
        SeedFile(path, content, executable=executable)
        for path, content, executable in template_files(template.id, profile)
    ]
    files.append(
        SeedFile(
            template.docs_path,
            render_deployment_doc(
                template,
                project_name=project.name,
                preview_url=preview_url,
                # Only a composed scaffold's document says what the plan
                # decided; for a flat template there is nothing to report and
                # the section would be noise.
                profile=profile if is_composed_scaffold(template.id) else None,
            )
            + _footer(project),
        )
    )
    return files


# --------------------------------------------------------------------------- #
# Seeding a repository that already has content (plan 0027 M4)
# --------------------------------------------------------------------------- #

# Where every derived document goes in an imported repository: one folder the
# platform owns, so nothing it writes can land on a file the team wrote.
PROMPTZONE_DOCS_DIR = "docs/promptzone"

# Derived views that are always relocated into PROMPTZONE_DOCS_DIR for an
# imported repository, whether or not the original path is taken: a repo with
# no README today may well grow one, and a platform file squatting on the
# conventional path would be in the way.
_ALWAYS_RELOCATED = frozenset(
    {
        "README.md",
        "docs/scope.md",
        "docs/architecture.md",
        "docs/tasks.md",
        "docs/conventions.md",
        "docs/policy-scope.md",
    }
)

# Written where tools look for them — AGENTS.md at the root, the constitution
# where the engine's `withConstitution()` reads it — but only if the path is
# free. A team's own AGENTS.md is their agents' instructions; ours goes beside
# it instead.
_RELOCATE_IF_TAKEN = {
    "AGENTS.md": f"{PROMPTZONE_DOCS_DIR}/AGENTS.md",
    ".specify/memory/constitution.md": f"{PROMPTZONE_DOCS_DIR}/constitution.md",
}

_WORKFLOWS_DIR = ".github/workflows/"


@dataclass(frozen=True)
class SeedPlan:
    """What a seed commit into an existing repository will do, before it
    does it — the same object the commit is built from and the seed preview
    reports, so the two cannot disagree."""

    files: list[SeedFile]
    # (original path, path actually written)
    relocated: list[tuple[str, str]]
    # Paths not written because a file is already there.
    skipped: list[str]
    # Paths that cannot be skipped safely; a non-empty list means no commit.
    conflicts: list[str]


def proper_prefixes(path: str) -> list[str]:
    parts = path.split("/")
    return ["/".join(parts[:depth]) for depth in range(1, len(parts))]


def seed_candidate_paths(
    seed_files: list[SeedFile], deployment_files: list[SeedFile]
) -> set[str]:
    """Every path `fit_to_existing_repo` could decide to write for this seed,
    relocations included — what the no-overwrite check has to know about
    when the repository's full listing is not available (a truncated tree,
    app/api/sync.py::_existing_tree)."""
    candidates: set[str] = set()
    for seed_file in [*seed_files, *deployment_files]:
        candidates.add(seed_file.path)
        candidates.add(f"{PROMPTZONE_DOCS_DIR}/{posixpath.basename(seed_file.path)}")
        if seed_file.path in _RELOCATE_IF_TAKEN:
            candidates.add(_RELOCATE_IF_TAKEN[seed_file.path])
    return candidates


def fit_to_existing_repo(
    seed_files: list[SeedFile],
    deployment_files: list[SeedFile],
    existing_paths: frozenset[str],
    existing_dirs: frozenset[str] = frozenset(),
) -> SeedPlan:
    """Rewrite a seed so it never overwrites anything `existing_paths` names.

    `existing_paths` is every non-directory entry — files, symlinks and
    submodule gitlinks alike — and `existing_dirs` the directories (those
    implied by `existing_paths` are added here). A target counts as taken
    when, compared case-insensitively (a checkout on macOS or Windows cannot
    hold both `AGENTS.md` and `agents.md`), it is an existing entry, an
    existing directory, or lies beneath an existing file or submodule — a
    `docs` submodule blocks `docs/promptzone/scope.md` as surely as a file at
    that exact path would.

    Derived documents move under `docs/promptzone/` (always, or only when
    taken — see the two tables above), and anything still colliding after
    that is dropped, including a `docs/promptzone/*` file a previous import
    already left there. Deployment scaffold files that already exist are
    skipped one at a time: the team's own `Dockerfile` stays theirs.

    A workflow file is the exception, and it is a conflict rather than a
    skip. Skipping `.github/workflows/deploy.yml` would leave a project whose
    secrets, variables and preview state all say "deployable" with the
    team's unrelated workflow behind them — and merging into it is what ADR
    0024 forbids outright. So the caller refuses (`deploy_workflow_conflict`)
    and the Tech Lead either picks no template or moves that file first.
    """
    entries = {p.lower() for p in existing_paths}
    dirs = {d.lower() for d in existing_dirs}
    for path in entries:
        dirs.update(proper_prefixes(path))

    def taken(path: str) -> bool:
        lowered = path.lower()
        return (
            lowered in entries
            or lowered in dirs
            or any(prefix in entries for prefix in proper_prefixes(lowered))
        )

    files: list[SeedFile] = []
    relocated: list[tuple[str, str]] = []
    skipped: list[str] = []
    conflicts: list[str] = []

    for seed_file in seed_files:
        target = seed_file.path
        if target in _ALWAYS_RELOCATED:
            target = f"{PROMPTZONE_DOCS_DIR}/{posixpath.basename(target)}"
        elif target in _RELOCATE_IF_TAKEN and taken(target):
            target = _RELOCATE_IF_TAKEN[target]
        if taken(target):
            skipped.append(target)
            continue
        if target != seed_file.path:
            relocated.append((seed_file.path, target))
            seed_file = SeedFile(target, seed_file.content, seed_file.executable)
        files.append(seed_file)

    for seed_file in deployment_files:
        if seed_file.path.startswith("docs/"):
            # The template's `docs/deployment.md` is a derived document like
            # the ones above, not scaffold, so it moves with them.
            target = f"{PROMPTZONE_DOCS_DIR}/{posixpath.basename(seed_file.path)}"
            if taken(target):
                skipped.append(target)
            else:
                relocated.append((seed_file.path, target))
                files.append(SeedFile(target, seed_file.content, seed_file.executable))
        elif not taken(seed_file.path):
            files.append(seed_file)
        elif seed_file.path.startswith(_WORKFLOWS_DIR):
            conflicts.append(seed_file.path)
        else:
            skipped.append(seed_file.path)

    return SeedPlan(files=files, relocated=relocated, skipped=skipped, conflicts=conflicts)
