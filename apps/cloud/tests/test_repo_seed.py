def test_no_template_builds_no_deployment_files():
    """Backward compatibility at the builder level: the deployment builder is
    separate from build_seed_files precisely so a project with no template
    cannot be affected by it at all."""
    project = Project(name="P", workspace_id="w", owner_id="u")
    assert build_deployment_files(project, None) == []


def test_template_builds_scaffold_workflow_and_docs():
    project = Project(
        name="Rocket",
        workspace_id="w",
        owner_id="u",
        deployment_config=DeploymentConfig(template_id="static-r2"),
    )
    files = build_deployment_files(project, "https://preview.test/p/")
    paths = {f.path for f in files}
    assert ".github/workflows/deploy.yml" in paths
    assert "site/index.html" in paths
    assert "docs/deployment.md" in paths

    doc = next(f.content for f in files if f.path == "docs/deployment.md")
    assert "https://preview.test/p/" in doc
    assert "Rocket" in doc


def test_withdrawn_template_seeds_nothing_rather_than_failing():
    """A selection that no longer resolves must not cost the project its repo
    and its AI context — those are still worth having."""
    project = Project(
        name="P",
        workspace_id="w",
        owner_id="u",
        deployment_config=DeploymentConfig(template_id="retired-template"),
    )
    assert build_deployment_files(project, None) == []


def test_deployment_files_do_not_collide_with_the_derived_documents():
    """The two builders are concatenated into one commit, so a shared path
    would mean one silently overwriting the other in the tree."""
    project = Project(
        name="P",
        workspace_id="w",
        owner_id="u",
        deployment_config=DeploymentConfig(template_id="static-r2"),
    )
    derived = {f.path for f in build_seed_files(project, {})}
    deployment = {f.path for f in build_deployment_files(project, None)}
    assert derived.isdisjoint(deployment)


def test_docker_compose_is_a_customer_owned_provider_template():
    template = get_template("docker-compose")
    assert template is not None
    assert template.provider_credential_kind == "ssh-docker"
    # Nobody mints the URL of a server the customer administers, so a human
    # names it and both sides read the same stored value.
    assert template.url_kind == "platform"
    assert template.platform_url_source == "project_value:public_url"
    assert template.provider in PROVIDERS


def test_docker_compose_seeds_a_dockerfile_a_compose_file_and_the_fixed_workflow():
    paths = {path for path, _, _ in template_files("docker-compose")}
    assert "Dockerfile" in paths
    assert "compose.yaml" in paths
    assert ".github/workflows/deploy.yml" in paths
    # The layout directories are an implementation detail of the composed
    # scaffold and must never reach a customer's repository.
    assert not any(p.startswith(("base/", "runtimes/", "services/")) for p in paths)


def test_docker_compose_opens_a_deployment_first_and_never_weakens_host_checking():
    workflow = next(
        content
        for path, content, _ in template_files("docker-compose")
        if path == ".github/workflows/deploy.yml"
    )
    # Opening the deployment before the build is what lets the Preview tab show
    # "building" immediately instead of nothing until the deploy finishes.
    assert workflow.index("Open deployment") < workflow.index("Build the image")
    assert "environment_url" in workflow
    # A pull request must never reach the deploy credential — and here that
    # credential is shell access to the customer's host.
    assert "pull_request_target" not in workflow
    # The key travels to whichever machine the admin's own host key names.
    assert "StrictHostKeyChecking yes" in workflow
    assert "StrictHostKeyChecking=no" not in workflow


