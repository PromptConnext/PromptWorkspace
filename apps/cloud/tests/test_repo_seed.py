def test_empty_stage_docs_still_yield_agents_and_readme_stubs():
    project = _project()
    files = build_seed_files(project, {})
    by_path = {f.path: f.content for f in files}

    assert "AGENTS.md" in by_path
    assert "No constitution has been generated" in by_path["AGENTS.md"]
    assert "README.md" in by_path
    assert "No scope/spec has been generated" in by_path["README.md"]
    # No dedicated doc for stages with nothing to show.
    assert "docs/scope.md" not in by_path
    assert "docs/architecture.md" not in by_path
    assert "docs/tasks.md" not in by_path
    # Conventions always ships — as a stub pointing at AGENTS.md when there's
    # no constitution to scan.
    assert "docs/conventions.md" in by_path
    assert "AGENTS.md" in by_path["docs/conventions.md"]


