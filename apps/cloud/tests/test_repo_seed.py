def _project(**overrides) -> Project:
    defaults = dict(name="Rocket", workspace_id="ws-1", owner_id="alice")
    defaults.update(overrides)
    return Project(**defaults)


def test_full_stage_docs_produce_all_files():
    project = _project()
    constitution = (
        "# Constitution\n\nSome rules.\n\n"
        "## Conventions\n\n- Use snake_case.\n- No TODOs.\n\n"
        "## Other\n\nMore stuff."
    )
    stage_docs = {
        "constitution": constitution,
        "specify": "# Scope\n\nBuild a rocket.",
        "plan": "# Architecture\n\nUse staged boosters.",
        "tasks": "# Tasks\n\nT001: build stage one.",
    }
    files = build_seed_files(project, stage_docs)
    paths = {f.path for f in files}
    assert paths == {
        "AGENTS.md",
        "README.md",
        "docs/scope.md",
        "docs/architecture.md",
        "docs/tasks.md",
        "docs/conventions.md",
        ".specify/memory/constitution.md",
    }

    by_path = {f.path: f.content for f in files}
    assert "Some rules." in by_path["AGENTS.md"]
    assert "Build a rocket." in by_path["README.md"]
    assert by_path["docs/scope.md"].startswith("# Scope")
    assert "Use staged boosters." in by_path["docs/architecture.md"]
    assert "T001" in by_path["docs/tasks.md"]
    assert "Use snake_case." in by_path["docs/conventions.md"]
    assert "Other" not in by_path["docs/conventions.md"]
    assert "Some rules." in by_path[".specify/memory/constitution.md"]


