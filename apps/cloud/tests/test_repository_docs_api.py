def test_a_sync_racing_another_ends_with_one_pull_request(client: TestClient):
    """Two syncs from the same head: the second finds no PR, then loses the
    branch name to the first, re-reads, and adds to the first one's PR."""
    pid = _created_project(client)
    _write_stage(client, pid, "plan", V2_PLAN)
    fake, full_name, branch = _race_branch(client)
    head = fake.branch_heads[full_name]
    asyncio.run(fake.create_branch(TOKEN, full_name, branch, head))
    asyncio.run(fake.create_pull_request(TOKEN, full_name, branch, "main", "t", "b"))
    real_find = fake.find_open_pull_request
    calls = []

    async def first_misses(token, repo, prefix, base, author=None):
        calls.append(prefix)
        if len(calls) == 1:
            return None
        return await real_find(token, repo, prefix, base, author=author)

    fake.find_open_pull_request = first_misses

    res = _sync(client, pid)

    assert res.status_code == 200, res.text
    assert len(calls) == 2
    assert len(fake.pull_requests) == 1
    assert res.json()["pr_number"] == 1 and res.json()["branch"] == branch
    assert fake.commits[-1]["branch"] == branch
    assert fake.branch_heads[full_name] == head


