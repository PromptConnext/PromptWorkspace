_ISO_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def test_status_stays_current_on_a_later_day(client: TestClient, monkeypatch):
    """The seed footer carries no date: a status read the day after creation
    must not report every document as changed."""
    pid = _created_project(client)
    fake = _fake(client)
    committed = fake.sha_files[fake.branch_heads[_repo_name(client)]]
    footers = [
        line
        for content in committed.values()
        for line in content.splitlines()
        if "Generated by PromptWorkspace for project" in line
    ]
    assert footers
    assert not any(_ISO_DATE.search(line) for line in footers), footers

    project = client.app.state.repository.get_project(pid)
    today = [(f.path, f.content) for f in build_seed_files(project, STAGE_DOCS)]

    class _Tomorrow(datetime):
        @classmethod
        def now(cls, tz=None):
            return datetime.now(tz) + timedelta(days=1)

    # Both import styles: `datetime.datetime.now()` and a module-level
    # `from datetime import datetime` (raising=False: the seed needs neither).
    monkeypatch.setattr("datetime.datetime", _Tomorrow)
    monkeypatch.setattr("app.integrations.repo_seed.datetime", _Tomorrow, raising=False)

    assert [(f.path, f.content) for f in build_seed_files(project, STAGE_DOCS)] == today
    states = _states(_status(client, pid))
    assert states and set(states.values()) == {"current"}


