def _states(body: dict) -> dict[str, str]:
    return {f["path"]: f["state"] for f in body["files"]}


def _sync(client: TestClient, pid: str, headers: dict = ALICE):
    return client.post(f"/projects/{pid}/repository/sync-docs", headers=headers)


